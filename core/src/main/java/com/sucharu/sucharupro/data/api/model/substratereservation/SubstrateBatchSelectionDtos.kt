fun BatchLotSelectionResult.toDto(): BatchLotSelectionResponseDto {
    return BatchLotSelectionResponseDto(
        selectionId = selectionId,
        tenantId = tenantId,
        orderId = specification.orderId,
        orderItemId = specification.orderItemId,
        executionJobId = specification.executionJobId,
        workOrderId = specification.workOrderId,
        reservationId = specification.reservationId,
        productId = specification.productId,
        sku = specification.sku,
        requestedMaterialName = specification.requestedMaterialName,
        stockType = specification.stockType.name,
        targetGsm = specification.targetGsm,
        requiredSheetWidthMm = specification.requiredSheetDimension.width,
        requiredSheetHeightMm = specification.requiredSheetDimension.height,
        requiredGrainDirection = specification.requiredGrainDirection.name,
        requiredSheets = requiredSheets,
        allocatedSheets = allocatedSheets,
        deficitSheets = deficitSheets,
        allocatedReams = allocatedReams,
        allocatedWeightKg = allocatedWeightKg,
        status = status.name,
        isFullySatisfied = isFullySatisfied,
        isMultiBatchFulfillment = isMultiBatchFulfillment,
        primarySelectedBatchNumber = primarySelectedBatchNumber,
        primarySelectedLotNumber = primarySelectedLotNumber,
        primaryWarehouseId = primaryWarehouseId,
        overallCompatibilityScore = overallCompatibilityScore,
        selectionExplanation = selectionExplanation,
        masterIntegrityHash = masterIntegrityHash,
        isConfirmedAndAllocated = isConfirmedAndAllocated,
        selectedBatches = selectedBatches.map {
            SelectedBatchAllocationDto(
                allocationId = it.allocationId,
                selectionId = it.selectionId,
                warehouseId = it.warehouseId,
                warehouseName = it.warehouseName,
                locationId = it.locationId,
                batchNumber = it.batchNumber,
                lotNumber = it.lotNumber,
                sku = it.sku,
                allocatedSheets = it.allocatedSheets,
                allocatedReams = it.allocatedReams,
                allocatedWeightKg = it.allocatedWeightKg,
                sheetWidthMm = it.sheetDimension.width,
                sheetHeightMm = it.sheetDimension.height,
                grainDirection = it.grainDirection.name,
                isRotated = it.isRotated,
                matchScore = it.matchScore
            )
        },
        evaluatedCandidates = evaluatedCandidates.map {
            EvaluatedBatchCandidateDto(
                candidate = BatchLotCandidateDto(
                    candidateId = it.candidate.candidateId,
                    warehouseId = it.candidate.warehouseId,
                    warehouseName = it.candidate.warehouseName,
                    locationId = it.candidate.locationId,
                    locationCode = it.candidate.locationCode,
                    productId = it.candidate.productId,
                    sku = it.candidate.sku,
                    productName = it.candidate.productName,
                    batchNumber = it.candidate.batchNumber,
                    lotNumber = it.candidate.lotNumber,
                    supplierLotReference = it.candidate.supplierLotReference,
                    stockType = it.candidate.stockType.name,
                    gsm = it.candidate.gsm,
                    sheetWidthMm = it.candidate.sheetDimension.width,
                    sheetHeightMm = it.candidate.sheetDimension.height,
                    grainDirection = it.candidate.grainDirection.name,
                    onHandPhysicalSheets = it.candidate.onHandPhysicalSheets,
                    reservedSheets = it.candidate.reservedSheets,
                    hardAllocatedSheets = it.candidate.hardAllocatedSheets,
                    usableSheets = it.candidate.usableSheets,
                    receivedTimestamp = it.candidate.receivedTimestamp,
                    expiryTimestamp = it.candidate.expiryTimestamp,
                    qualityRating = it.candidate.qualityRating,
                    status = it.candidate.status
                ),
                dimensionMatch = it.dimensionMatch.name,
                grainCompatibility = it.grainCompatibility.name,
                isRotated = it.isRotated,
                gsmMatchScore = it.gsmMatchScore,
                overallScore = it.overallScore,
                isEligible = it.isEligible,
                allocatedSheetsFromThisBatch = it.allocatedSheetsFromThisBatch,
                allocatedReams = it.allocatedReams,
                allocatedWeightKg = it.allocatedWeightKg,
                evaluationReasons = it.evaluationReasons,
                rejectionReasons = it.rejectionReasons
            )
        },
        selectedAt = selectedAt,
        selectedBy = selectedBy,
        confirmedAt = confirmedAt,
        confirmedBy = confirmedBy
    )
}
